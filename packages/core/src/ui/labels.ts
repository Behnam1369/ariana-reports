export type LabelKey = keyof typeof DEFAULT_LABELS;
export type Labels = { [K in LabelKey]: string };

export function mergeLabels(overrides?: Partial<Labels>): Labels {
  return { ...DEFAULT_LABELS, ...overrides };
}

/** Fills `{name}` placeholders: `formatLabel('Page {page}', { page: 2 })` → "Page 2". Unknown names are kept. */
export function formatLabel(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, key: string) => (key in values ? String(values[key]) : m));
}
